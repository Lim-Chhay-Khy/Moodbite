// All restaurants that serve a given food, closest first.
export function getRestaurantsForFood(foodId) {
  return restaurants
    .filter((restaurant) => restaurant.foods.includes(foodId))
    .sort((a, b) => a.distance - b.distance)
}

export function getRestaurantById(id) {
  return restaurants.find((restaurant) => restaurant.id === id)
}

export default restaurants
